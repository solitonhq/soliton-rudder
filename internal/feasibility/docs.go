var categoryTitles = map[Category]string{
	CatResources:   "Resources",
	CatReliability: "Reliability",
	CatSecurity:    "Security",
	CatMaintenance: "Maintenance",
}

// RulesMarkdown renders the built-in rule catalogue (docs/ASSESSMENT-RULES.md).
func RulesMarkdown() string {
	var b strings.Builder
	b.WriteString("# Assessment rules\n\n")
	b.WriteString("<!-- Generated by `go run ./cmd/gendocs`. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "Soliton Rudder's cluster assessment runs %d built-in, read-only checks against a snapshot of your cluster.\n", len(Rules))
	b.WriteString("This page lists every check, what it looks for, how severe a finding can be, and how to fix it.\n")
	b.WriteString("See the [user guide](USER-GUIDE.md#assessments) for how scoring works.\n\n")
	b.WriteString("System namespaces (`kube-*`) are excluded from workload hygiene and security checks. Workload checks run once per\n")
	b.WriteString("Deployment / StatefulSet / DaemonSet / CronJob / Job template (and bare pods), not once per replica.\n")
	b.WriteString("Checks that need metrics-server are skipped (and reported as skipped) when it is not installed.\n\n")
	for _, c := range Categories {
		fmt.Fprintf(&b, "## %s\n\n", categoryTitles[c])
		for _, r := range Rules {
			if r.Category != c {
				continue
			}
			fmt.Fprintf(&b, "### %s\n\n", r.Title)
			fmt.Fprintf(&b, "`%s` · severity: %s\n\n", r.ID, ruleSeverities[r.ID])
			fmt.Fprintf(&b, "%s\n\n**How to fix:** %s\n\n", r.Description, r.Remediation)
		}
	}
	b.WriteString("## Writing your own checks\n\nPlugins can contribute additional rules; see the [plugin guide](PLUGINS.md).\n")
	return b.String()
}
