#!/usr/bin/env python3
"""Generates THIRD_PARTY_NOTICES.txt: licenses of everything shipped inside the app.

Go dependencies come from `go-licenses` (go install github.com/google/go-licenses/v2@latest);
frontend runtime dependencies come from `license-checker-rseidelsohn` via npx (production deps only —
build-time tools such as Tailwind/Vite are not part of the shipped app).
"""
import json, os, re, shutil, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.txt"
OWN_MODULE = "soliton-rudder"
APACHE_MARK = "Apache License\n                           Version 2.0, January 2004"

def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw).stdout

def read(p: Path) -> str:
    try:
        return p.read_text(errors="replace").strip()
    except OSError:
        return ""

def go_packages():
    gl = shutil.which("go-licenses") or str(Path.home() / "go/bin/go-licenses")
    tmpl = "{{range .}}{{.Name}}\t{{.Version}}\t{{.LicenseName}}\t{{.LicenseURL}}\n{{end}}"
    tf = tempfile.NamedTemporaryFile("w", suffix=".tmpl", delete=False); tf.write(tmpl); tf.close()
    out = run([gl, "report", ".", "--template", tf.name, "--ignore", OWN_MODULE], cwd=ROOT)
    save = Path(tempfile.mkdtemp())
    shutil.rmtree(save)
    subprocess.run([gl, "save", ".", "--save_path", str(save), "--ignore", OWN_MODULE], cwd=ROOT, check=True, capture_output=True)
    pkgs = {}
    for line in out.splitlines():
        parts = line.split("\t")
        if len(parts) < 3 or parts[0].startswith(OWN_MODULE):
            continue
        name, version, lic = parts[0], parts[1], parts[2]
        d = save / name
        text = read(d / "LICENSE") or next((read(f) for f in sorted(d.glob("LICEN*")) + sorted(d.glob("COPYING*"))), "")
        notice = read(d / "NOTICE")
        pkgs[name] = dict(name=name, version=version, license=lic, text=text, notice=notice, url=parts[3] if len(parts) > 3 else "")
    return pkgs

def npm_packages():
    out = run(["npx", "--yes", "license-checker-rseidelsohn", "--production", "--excludePrivatePackages", "--json"], cwd=ROOT / "frontend")
    pkgs = {}
    for key, info in json.loads(out).items():
        name, _, version = key.rpartition("@")
        text = read(Path(info["licenseFile"])) if info.get("licenseFile") else ""
        pkgs[name] = dict(name=name, version=version, license=str(info.get("licenses", "")), text=text, notice="", url=info.get("repository", ""))
    return pkgs

def main():
    go, npm = go_packages(), npm_packages()
    apache_text = next((p["text"] for p in go.values() if APACHE_MARK in p["text"]), "")
    lines = [
        "THIRD-PARTY SOFTWARE NOTICES",
        "",
        "Soliton Rudder includes the open-source software listed below. Each component is licensed by its",
        "authors under the terms shown; none of them is affiliated with or endorses Soliton Rudder.",
        "(Generated by scripts/gen_notices.py — do not edit by hand.)",
        "",
    ]
    def section(title, pkgs):
        lines.extend(["=" * 78, title, "=" * 78, ""])
        for name in sorted(pkgs):
            p = pkgs[name]
            lines.append(f"--- {p['name']} {p['version']}  [{p['license']}]")
            if p["url"]:
                lines.append(f"    {p['url']}")
            text = p["text"]
            if apache_text and text == apache_text:
                text = "(Apache License 2.0 — full text reproduced once at the end of this file.)"
            lines.append("")
            lines.append(text or "(license text not found in the package; see the project URL above)")
            if p["notice"]:
                lines.extend(["", "NOTICE:", p["notice"]])
            lines.append("")
    section("GO MODULES", go)
    section("FRONTEND PACKAGES (bundled)", npm)
    if apache_text:
        lines.extend(["=" * 78, "APACHE LICENSE 2.0 (full text)", "=" * 78, "", apache_text, ""])
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(go)} Go modules, {len(npm)} npm packages, {OUT.stat().st_size // 1024} KB")
    missing = [p["name"] for p in list(go.values()) + list(npm.values()) if not p["text"]]
    if missing:
        print("WARNING: no license text found for:", ", ".join(missing), file=sys.stderr)

main()
